mod firmware;
mod renode;
mod studio;

use std::fs;
use std::path::{Path, PathBuf};

use serde::Serialize;

use crate::load::Repository;
use crate::resolve::{ResolveError, resolve};

pub const GENERATED_MARKER: &str = "@generated by `drone codegen`; edit hardware/ and regenerate";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Artifact {
    pub path: PathBuf,
    pub kind: ArtifactKind,
    pub contents: String,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ArtifactKind {
    FirmwareConstants,
    FirmwareIndex,
    SimulatorModel,
    RenodePlatform,
    StudioLayout,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum FileStatus {
    Unchanged,
    Written,
    Stale,
    Missing,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct FileReport {
    pub path: String,
    pub kind: ArtifactKind,
    pub status: FileStatus,
    pub bytes: usize,
}

pub fn firmware_dir(repo_root: &Path) -> PathBuf {
    repo_root.join("firmware/flight-config/src/generated")
}

pub fn generate(repo: &Repository) -> Result<Vec<Artifact>, ResolveError> {
    let mut out = Vec::new();
    let mut firmware_modules = Vec::new();
    let mut boards_done = Vec::new();
    for id in repo.airframes.keys() {
        let r = resolve(repo, id)?;
        let mut model_json = serde_json::to_string_pretty(&r.model).unwrap_or_default();
        model_json.push('\n');
        out.push(Artifact {
            path: PathBuf::from(format!("hardware/generated/{id}/airframe_model.json")),
            kind: ArtifactKind::SimulatorModel,
            contents: model_json,
        });
        out.push(Artifact {
            path: PathBuf::from(format!("hardware/generated/{id}/board_layout.json")),
            kind: ArtifactKind::StudioLayout,
            contents: studio::board_layout(&r),
        });
        out.push(Artifact {
            path: PathBuf::from(format!("firmware/flight-config/src/generated/{id}.rs")),
            kind: ArtifactKind::FirmwareConstants,
            contents: firmware::constants(&r),
        });
        firmware_modules.push(id.clone());
        if !boards_done.contains(&r.board.id) {
            boards_done.push(r.board.id.clone());
            out.push(Artifact {
                path: PathBuf::from(format!("emu/generated/{}.repl", r.board.id)),
                kind: ArtifactKind::RenodePlatform,
                contents: renode::platform(&r),
            });
        }
    }
    out.push(Artifact {
        path: PathBuf::from("firmware/flight-config/src/generated/mod.rs"),
        kind: ArtifactKind::FirmwareIndex,
        contents: firmware::index(&firmware_modules),
    });
    out.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(out)
}

fn status_of(repo_root: &Path, a: &Artifact) -> FileStatus {
    match fs::read_to_string(repo_root.join(&a.path)) {
        Ok(existing) if existing == a.contents => FileStatus::Unchanged,
        Ok(_) => FileStatus::Stale,
        Err(_) => FileStatus::Missing,
    }
}

pub fn check(repo_root: &Path, artifacts: &[Artifact]) -> Vec<FileReport> {
    artifacts
        .iter()
        .map(|a| FileReport {
            path: a.path.to_string_lossy().replace('\\', "/"),
            kind: a.kind,
            status: status_of(repo_root, a),
            bytes: a.contents.len(),
        })
        .collect()
}

pub fn write(repo_root: &Path, artifacts: &[Artifact]) -> std::io::Result<Vec<FileReport>> {
    let mut reports = Vec::new();
    for a in artifacts {
        let status = match status_of(repo_root, a) {
            FileStatus::Unchanged => FileStatus::Unchanged,
            _ => {
                let path = repo_root.join(&a.path);
                if let Some(parent) = path.parent() {
                    fs::create_dir_all(parent)?;
                }
                fs::write(&path, &a.contents)?;
                FileStatus::Written
            }
        };
        reports.push(FileReport {
            path: a.path.to_string_lossy().replace('\\', "/"),
            kind: a.kind,
            status,
            bytes: a.contents.len(),
        });
    }
    Ok(reports)
}

pub(crate) fn f32_literal(v: f64) -> String {
    let f = v as f32;
    let s = format!("{f:?}");
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}
